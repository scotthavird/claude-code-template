#!/usr/bin/env tsx
/**
 * docs-gen: spec + rendered outputs -> docs pages.
 *
 *   tsx docs-gen/src/index.ts [--slug <slug>]
 *
 * For each feature with a compiled film:
 *   docs/features/<slug>.md              the feature page
 *   docs/features/<slug>/loop.gif        committed (small, autoplays on GitHub)
 *   docs/features/<slug>/poster.png      committed
 * Then regenerates docs/features/README.md (gallery) and the newest three
 * entries between <!-- showcase:start --> / <!-- showcase:end --> in README.md.
 *
 * MP4/WebM are NOT committed: the page links to GitHub Release assets
 * (tag `showcase-<slug>`), uploaded separately (see showcase/README.md).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { FilmData } from "../../studio/src/lib/film";
import { buildCues, buildTimeline } from "../../studio/src/lib/timeline";

const here = path.dirname(fileURLToPath(import.meta.url));
const SHOWCASE = path.resolve(here, "..", "..");
const ROOT = path.resolve(SHOWCASE, "..");
const DOCS = path.join(ROOT, "docs", "features");

const argv = process.argv.slice(2);
const only = (() => {
  const i = argv.indexOf("--slug");
  return i >= 0 ? argv[i + 1] : argv.find((a) => !a.startsWith("--"));
})();

const repoUrl = (() => {
  const pkg = JSON.parse(
    fs.readFileSync(path.join(ROOT, "package.json"), "utf8"),
  ) as { repository?: { url?: string } | string };
  const raw =
    typeof pkg.repository === "string"
      ? pkg.repository
      : (pkg.repository?.url ?? "");
  return (
    raw.replace(/^git\+/, "").replace(/\.git$/, "") ||
    "https://github.com/OWNER/REPO"
  );
})();

// Films are served from Havoptic's shared R2 media bucket
// (key layout: showcase/<repo>/<slug>/<file>). Override with SHOWCASE_MEDIA_BASE.
const repoName = repoUrl.split("/").pop() ?? "repo";
const MEDIA_BASE =
  process.env.SHOWCASE_MEDIA_BASE ??
  `https://media.havoptic.com/showcase/${repoName}`;
const releaseBase = (slug: string) => `${MEDIA_BASE}/${slug}`;

const mmss = (s: number) =>
  `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, "0")}`;

function loadFilm(slug: string): FilmData | null {
  const p = path.join(
    SHOWCASE,
    "studio",
    "public",
    "features",
    slug,
    "film.json",
  );
  return fs.existsSync(p)
    ? (JSON.parse(fs.readFileSync(p, "utf8")) as FilmData)
    : null;
}

function page(
  film: FilmData,
  assets: {
    gif: boolean;
    poster: boolean;
    manifest: { file: string; bytes: number }[];
  },
): string {
  const s = film.spec;
  const slug = s.slug;
  const rel = releaseBase(slug);
  const tl = buildTimeline(film, "hero");
  const total = tl.total / tl.fps;
  const cues = buildCues(film, tl);
  const size = (f: string) => {
    const m = assets.manifest.find((x) => x.file === f);
    return m ? ` (${(m.bytes / 1024 / 1024).toFixed(1)} MB)` : "";
  };
  const relDocs = (p: string) =>
    path.relative(DOCS, path.join(ROOT, p)).split(path.sep).join("/");
  const lines: string[] = [];
  lines.push(
    `<!-- Generated by showcase/docs-gen from showcase/features/${slug}/spec.yaml. Edit the spec, not this file. -->`,
  );
  lines.push(`# ${s.title}`);
  lines.push("");
  lines.push(
    `> **Claude Code v${s.version}** · ${s.category} · [changelog](${s.changelog.url})`,
  );
  lines.push("");
  if (assets.gif) {
    lines.push(
      `[![${s.name ?? s.title}: ${s.tagline}](${slug}/loop.gif)](${rel}/hero-16x9.mp4)`,
    );
    lines.push("");
  }
  lines.push(
    `▶ **Watch the ${Math.round(total)}s film:** [MP4 1080p](${rel}/hero-16x9.mp4)${size("hero-16x9.mp4")} · [WebM](${rel}/hero.webm)${size("hero.webm")} · ` +
      `[9:16](${rel}/social-9x16.mp4) · [1:1](${rel}/social-1x1.mp4) · [captions](${rel}/captions.vtt)`,
  );
  lines.push("");
  lines.push(
    `<!-- Film files live in the R2 bucket behind ${MEDIA_BASE}; upload them with:`,
  );
  lines.push(`     pnpm --dir showcase upload --slug ${slug} -->`);
  lines.push("");
  lines.push(`**${s.tagline}**`);
  lines.push("");
  lines.push(s.docs.summary.trim());
  lines.push("");
  lines.push("## How to enable");
  lines.push("");
  lines.push(`${s.enable.lead ?? "In"} \`${s.enable.file}\`:`);
  lines.push("");
  lines.push("```" + s.enable.lang);
  lines.push(s.enable.code.replace(/\n$/, ""));
  lines.push("```");
  lines.push("");
  if (s.enable.install) {
    lines.push("Or get it with the whole template:");
    lines.push("");
    lines.push("```bash");
    lines.push(s.enable.install);
    lines.push("```");
    lines.push("");
  }
  lines.push("## Try it in 60 seconds");
  lines.push("");
  s.docs.tryIt.forEach((t, i) => lines.push(`${i + 1}. ${t}`));
  lines.push("");
  lines.push("## What you just watched");
  lines.push("");
  lines.push(
    "A transcript of the film (also shipped as `captions.vtt`). Every terminal frame is a real `claude` session, recorded by the showcase pipeline; sped-up sections are labelled on screen.",
  );
  lines.push("");
  for (const c of cues) lines.push(`- **${mmss(c.start)}** ${c.text}`);
  lines.push("");
  lines.push("## Related");
  lines.push("");
  for (const r of s.docs.related) lines.push(`- [\`${r}\`](${relDocs(r)})`);
  lines.push(`- [Changelog](${s.changelog.url}): "${s.changelog.quote}"`);
  lines.push(
    `- Film source: [\`showcase/features/${slug}/spec.yaml\`](${relDocs(`showcase/features/${slug}/spec.yaml`)})`,
  );
  lines.push("");
  return lines.join("\n");
}

function main() {
  fs.mkdirSync(DOCS, { recursive: true });
  const slugs = fs
    .readdirSync(path.join(SHOWCASE, "features"))
    .filter((d) =>
      fs.existsSync(path.join(SHOWCASE, "features", d, "spec.yaml")),
    )
    .filter((d) => !only || d === only);
  for (const slug of slugs) {
    const film = loadFilm(slug);
    if (!film) {
      console.log(`skip ${slug}: not compiled`);
      continue;
    }
    const out = path.join(SHOWCASE, "out", slug);
    const assetDir = path.join(DOCS, slug);
    fs.mkdirSync(assetDir, { recursive: true });
    const copy = (f: string) => {
      const src = path.join(out, f);
      if (!fs.existsSync(src)) return false;
      fs.copyFileSync(src, path.join(assetDir, f));
      return true;
    };
    const gif =
      copy("loop.gif") || fs.existsSync(path.join(assetDir, "loop.gif"));
    const poster =
      copy("poster.png") || fs.existsSync(path.join(assetDir, "poster.png"));
    const manifestPath = path.join(out, "manifest.json");
    const manifest = fs.existsSync(manifestPath)
      ? (JSON.parse(fs.readFileSync(manifestPath, "utf8")).files as {
          file: string;
          bytes: number;
        }[])
      : [];
    fs.writeFileSync(
      path.join(DOCS, `${slug}.md`),
      page(film, { gif, poster, manifest }),
    );
    console.log(
      `wrote docs/features/${slug}.md (+ ${[gif && "loop.gif", poster && "poster.png"].filter(Boolean).join(", ")})`,
    );
  }

  // Gallery index over every documented feature, newest version first.
  const all = fs
    .readdirSync(path.join(SHOWCASE, "features"))
    .map((slug) => ({ slug, film: loadFilm(slug) }))
    .filter(
      (x): x is { slug: string; film: FilmData } =>
        !!x.film && fs.existsSync(path.join(DOCS, `${x.slug}.md`)),
    )
    .sort((a, b) =>
      b.film.spec.version.localeCompare(a.film.spec.version, undefined, {
        numeric: true,
      }),
    );
  const cell = (x: { slug: string; film: FilmData }, prefix: string) => {
    const s = x.film.spec;
    const img = fs.existsSync(path.join(DOCS, x.slug, "poster.png"))
      ? `<img src="${prefix}${x.slug}/poster.png" width="360" alt="${s.name ?? s.title}"><br>`
      : "";
    return `<td align="center" valign="top"><a href="${prefix}${x.slug}.md">${img}<b>${s.name ?? s.title}</b></a><br><sub>v${s.version} · ${s.category}</sub><br><sub>${s.tagline}</sub></td>`;
  };
  const grid = (items: typeof all, prefix: string) => {
    const rows: string[] = [];
    for (let i = 0; i < items.length; i += 2)
      rows.push(
        `<tr>${items
          .slice(i, i + 2)
          .map((x) => cell(x, prefix))
          .join("")}</tr>`,
      );
    return `<table>\n${rows.join("\n")}\n</table>`;
  };
  const index = [
    "<!-- Generated by showcase/docs-gen. -->",
    "# Feature films",
    "",
    "Each film is recorded from a real `claude` session and rendered by the [Feature Showcase Pipeline](../../showcase/README.md).",
    "Click a poster for the page: how to enable it, how to try it, and a transcript.",
    "",
    grid(all, ""),
    "",
  ].join("\n");
  fs.writeFileSync(path.join(DOCS, "README.md"), index);
  console.log(
    `wrote docs/features/README.md (${all.length} feature${all.length === 1 ? "" : "s"})`,
  );

  const readme = path.join(ROOT, "README.md");
  const text = fs.readFileSync(readme, "utf8");
  const start = "<!-- showcase:start -->";
  const end = "<!-- showcase:end -->";
  if (text.includes(start) && text.includes(end)) {
    const block = `${start}\n${grid(all.slice(0, 3), "docs/features/")}\n${end}`;
    fs.writeFileSync(
      readme,
      text.replace(new RegExp(`${start}[\\s\\S]*?${end}`), block),
    );
    console.log("updated README.md showcase block");
  }
}

main();
